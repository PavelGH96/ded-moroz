// Текст письма от Деда Мороза. Один и тот же текст на сайте (предпросмотр), в PDF, на подарочной странице и в Telegram.
// Кусочки { t: текст, em: true } отмечают то, что вписали родители: на сайте они подсвечены,
// в PDF печатаются теми же чернилами, что и остальной текст.
// Получатель: ребёнок (recipient "child", по умолчанию) или взрослый ("adult").

export function years(n) {
  n = parseInt(n, 10);
  if (!n || n < 1 || n > 17) return "";
  const a = n % 10, b = n % 100;
  const w = a === 1 && b !== 11 ? "год" : a >= 2 && a <= 4 && (b < 12 || b > 14) ? "года" : "лет";
  return n + " " + w;
}

const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);
const dropDot = (s) => s.replace(/[.!…]+$/, "");
const yes = (v) => v === true || ["1", "true", "on", "yes"].includes(String(v ?? "").toLowerCase());

export function buildLetter(d) {
  const adult = d.recipient === "adult";
  const female = d.gender === "f";
  const g = (f, m) => (female ? f : m);
  const name = cap(clean(d.name));
  const praise = dropDot(clean(d.praise));
  const wish = dropDot(clean(d.wish));
  const gift = dropDot(clean(d.gift));
  const intro = [{ t: "Пишу тебе из Великого Устюга. За окном метёт метель, а в моей мастерской помощники заворачивают последние подарки и спорят, у кого бантик красивее." }];

  const greeting = name
    ? [{ t: "Здравствуй, " + g("дорогая", "дорогой") + " " }, { t: name, em: true }, { t: "!" }]
    : adult
      ? [{ t: g("Здравствуй, дорогая моя!", "Здравствуй, дорогой мой!") }]
      : [{ t: g("Здравствуй, моя юная подруга!", "Здравствуй, мой юный друг!") }];

  const p = [intro];
  if (adult) {
    p.push([{ t: "Этой ночью я заглянул и к тебе. Взрослые редко пишут мне письма, но я помню каждого, кто когда-то ждал меня у ёлки, и тебя тоже." }]);
    p.push(praise
      ? [{ t: "Мои помощники-снегири рассказали, что в этом году ты " }, { t: praise, em: true }, { t: ". Спасибо тебе! Такие люди и делают Новый год волшебным." }]
      : [{ t: "Мои помощники-снегири рассказали, сколько тепла ты подарил" + g("а", "") + " родным в этом году. Спасибо тебе! Такие люди и делают Новый год волшебным." }]);
    if (wish) p.push([{ t: "В новом году я желаю тебе " }, { t: wish, em: true }, { t: ". Пусть всё задуманное сбудется." }]);
    p.push(gift
      ? [{ t: "А про твою мечту я помню: " }, { t: gift, em: true }, { t: ". Загляни утром под ёлку!" }]
      : [{ t: "А твой подарок уже ждёт тебя под ёлкой." }]);
    p.push([{ t: "Береги себя и близких и не переставай верить в чудеса: они случаются и со взрослыми." }]);
    return { greeting, paragraphs: p, closing: "С любовью,", signature: "Дед Мороз" };
  }

  const n = parseInt(d.age, 10);
  const age = years(n);
  p.push([{ t: "Этой ночью я заглянул к тебе. Ты так сладко " + g("спала", "спал") + ", что я не стал тебя будить и ушёл на цыпочках, чтобы не скрипнула ни одна половица." }]);
  if (yes(d.child_letter)) p.push([{ t: "Твоё письмо до меня дошло! Я прочитал его два раза и положил в самую главную шкатулку, где храню самые добрые письма." }]);
  const praisePara = [];
  if (age) {
    const big = n <= 7 ? g("совсем большая девочка", "совсем большой мальчик") : g("совсем взрослая", "совсем взрослый");
    praisePara.push({ t: "Тебе уже " }, { t: age, em: true }, { t: " — " + big + "! " });
  }
  praisePara.push({ t: "Мои помощники-снегири весь год присматривали за тобой и рассказали, что ты " }, { t: praise || g("очень старалась и радовала родных", "очень старался и радовал родных"), em: true }, { t: ". Я очень тобой горжусь!" });
  p.push(praisePara);
  if (wish) p.push([{ t: "В новом году у меня к тебе маленькая просьба: постарайся " }, { t: wish, em: true }, { t: ". Я верю, что у тебя обязательно получится." }]);
  p.push(gift
    ? [{ t: "А про твоё желание я помню: " }, { t: gift, em: true }, { t: ". Загляни утром под ёлку!" }]
    : [{ t: "А твой подарок уже ждёт тебя под ёлкой." }]);
  p.push([{ t: "Расти " + g("доброй", "добрым") + ", береги родных и всегда верь в чудеса." }]);

  return { greeting, paragraphs: p, closing: "С любовью,", signature: "Дед Мороз" };
}

export function letterPlain(d) {
  const l = buildLetter(d);
  const text = (runs) => runs.map((r) => r.t).join("");
  return [text(l.greeting), ...l.paragraphs.map(text), l.closing + " твой " + l.signature].join("\n");
}
